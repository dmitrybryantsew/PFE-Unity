        /// <summary>
        /// Reports every missing reference and every wrong-length array, one per line, and returns true
        /// only when the asset is complete.
        ///
        /// <para>Deliberately a method rather than a silent property: a composition asset that lost its
        /// icon arrays still <i>loads</i>, and every view that reads it then draws nothing with no error
        /// anywhere — the failure mode this project has already been bitten by (the <c>spritesExist</c>
        /// lesson: a guard that checks a folder <i>exists</i>, not that it holds the right thing). A
        /// wrong <b>length</b> is reported as carefully as a null, because the icon arrays are positional
        /// contracts: 46 item icons is not "one short", it is a silent off-by-one on every icon id.</para>
        /// </summary>
        public bool Validate(out string report)
        {
            var problems = new System.Collections.Generic.List<string>();

            void Required(UnityEngine.Object o, string what)
            {
                if (o == null) problems.Add("MISSING: " + what);
            }

            void Sized(Sprite[] array, int expected, string what)
            {
                if (array == null) problems.Add($"MISSING: {what} (null)");
                else if (array.Length != expected)
                    problems.Add($"WRONG SIZE: {what} — expected {expected}, got {array.Length}");
            }

            Required(bezel, "bezel (visPipBuck 1155)");
            Required(crtScanlines, "crtScanlines (vispipe 1227)");
            Required(tabButtonNormal, "tabButtonNormal (ButPage 1143 frame 1)");
            Required(tabButtonActive, "tabButtonActive (ButPage 1143 frame 2)");
            Required(subCategoryButton, "subCategoryButton (butCatFon 1019)");
            Required(monitorRowTemplate, "monitorRowTemplate (visPipRItem 1129)");
            Required(hudMasterLayout, "hudMasterLayout (visualGUI 4651)");
            Required(healthBar, "healthBar (hpBar 4180)");
            Required(bossBar, "bossBar (hpBarBoss 4360)");
            Required(satsRadius, "satsRadius (4168)");
            Required(satsCell, "satsCell (4162)");
            Required(cursorArrow, "cursorArrow (349)");
            Required(cursorAim, "cursorAim (348)");
            Required(cursorPrecision, "cursorPrecision (347)");
            Required(cursorMagic, "cursorMagic (346)");
            Required(terminalFont, "terminalFont (Lucida Console)");

            Sized(monitorIcons, MonitorIconCount, "monitorIcons (trol 876 frames 1..15)");
            Sized(itemCategoryIcons, ItemIconCount, "itemCategoryIcons (itemIco 1112)");
            Sized(statusEffectIcons, StatusEffectIconCount, "statusEffectIcons (_effectIco_174 4453)");
            Sized(npcPortraits, NpcPortraitCount, "npcPortraits (visNPCIco 4844)");
            Sized(reloadBarFrames, ReloadBarFrameCount, "reloadBarFrames (reloadBar 4166)");
            Sized(petBarFrames, PetBarFrameCount, "petBarFrames (hp_bar4 4172)");
            Sized(skillIcons, SkillIconCount, "skillIcons (vskill 383 frames 1..16)");
            Sized(perkIcons, PerkIconCount, "perkIcons (vskill 383 frames 17..95)");

            // The label tables ARE the id contract, so a count that disagrees with them means one of
            // the two was updated without the other — every icon past the disagreement is then wrong.
            if (SkillLabels.Length != SkillIconCount)
                problems.Add($"WRONG SIZE: SkillLabels — expected {SkillIconCount}, got {SkillLabels.Length}");
            if (PerkLabels.Length != PerkIconCount)
                problems.Add($"WRONG SIZE: PerkLabels — expected {PerkIconCount}, got {PerkLabels.Length}");

            if (problems.Count == 0)
            {
                report = "PipBuckComposition: all references present and correctly sized.";
                return true;
            }

            var sb = new System.Text.StringBuilder();
            sb.AppendLine($"PipBuckComposition: {problems.Count} problem(s):");
            foreach (string p in problems) sb.AppendLine("  " + p);
            report = sb.ToString();
            return false;
        }
