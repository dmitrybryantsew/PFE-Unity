    /// <summary>
    /// Every art, audio and typography asset the in-game interface needs, in one place.
    ///
    /// <para><b>Why a single asset rather than per-view references.</b> The Oracle's interface is one
    /// connected device: the PipBuck bezel, its 15-row status monitor, the 18-row page lists, the HUD
    /// bars and the dialogue window all draw from the same symbol table, and the same item icon index
    /// (<c>itemIco</c>, 47 frames) is read by the inventory page, the vendor page, the container page and
    /// the HUD. Splitting the references across nine prefabs would let one page drift from another with
    /// nothing to notice it, and the icon index is a positional contract — icon <i>n</i> must mean the
    /// same thing everywhere. One definition asset makes that contract checkable in one place.</para>
    ///
    /// <para><b>Generated by</b> <c>PFE/Art/Import Game Interface</c>
    /// (<c>PFE.Editor.Importers.SWF.InterfaceImportWindow</c>). Do not hand-edit the sprite arrays: the
    /// importer rewrites the whole asset and will drop anything added by hand.</para>
    ///
    /// <para><b>Typography note.</b> The interface specification calls for a TextMeshPro SDF font, but
    /// this port uses the legacy <see cref="Font"/> pipeline instead, because that is what the project's
    /// one already-working Flash UI port does (<c>MainMenuSceneBootstrapper.CreateMenuFont</c> renders
    /// the main menu in Lucida Console through legacy <c>UnityEngine.UI.Text</c>). Introducing TMP here
    /// would mean a second text stack, three asmdef edits and an unverifiable font-atlas bake, for no
    /// gain the monospace TTF does not already give. The colour fidelity the specification actually
    /// cares about lives in <c>FlashTextStyle</c>, which is renderer-agnostic.</para>
    /// </summary>
